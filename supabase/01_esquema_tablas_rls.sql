-- Permisos de API

revoke all on schema private from public, anon;
revoke all on public.roles, public.perfiles, public.usuario_roles,
              public.autores, public.categorias, public.libros, public.libro_autor,
              public.inventarios, public.sucursales,
              public.carritos, public.carrito_detalles,
              public.pedidos, public.pedido_detalles,
              public.pedido_direcciones_entrega,
              public.movimientos_inventario, public.mensajes_contacto
from anon, authenticated;
revoke all on sequence public.pedidos_numero_seq from anon, authenticated;

grant usage on schema public to authenticated;
grant usage on schema private to authenticated;
grant execute on function private.es_admin() to authenticated;
grant execute on function private.es_personal() to authenticated;

grant select on public.roles, public.perfiles, public.usuario_roles to authenticated;
