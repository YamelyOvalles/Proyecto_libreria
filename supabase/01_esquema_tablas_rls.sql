grant select, update (estado_pago) on public.pedidos to authenticated;
grant select on public.pedido_detalles, public.pedido_direcciones_entrega to authenticated;
grant select on public.movimientos_inventario to authenticated;
grant select, insert, update (estado) on public.mensajes_contacto to authenticated;

