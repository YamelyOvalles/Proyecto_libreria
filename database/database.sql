    id uuid primary key default gen_random_uuid(),
    numero text not null unique default (
        'LQ-' || to_char(now(), 'YYYYMMDD') || '-' ||
        lpad(nextval('public.pedidos_numero_seq')::text, 6, '0')
    ),
    cliente_id uuid not null references public.perfiles(id) on delete restrict,
    cliente_nombre text not null,
    cliente_correo text not null,
    cliente_documento text,
    cliente_telefono text,
    metodo_entrega text not null check (metodo_entrega in ('domicilio', 'retiro')),
    sucursal_id bigint references public.sucursales(id) on delete restrict,
    metodo_pago text not null check (metodo_pago in ('contra_entrega', 'efectivo', 'tarjeta', 'transferencia')),
    estado text not null default 'pendiente' check (
        estado in ('pendiente', 'confirmado', 'procesando', 'listo_retiro',
                   'enviado', 'entregado', 'cancelado', 'devuelto')
