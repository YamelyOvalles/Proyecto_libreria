-- Devuelve true solamente para cuentas con rol administrativo.
create or replace function private.es_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
          from public.usuario_roles ur
          join public.roles r on r.id = ur.rol_id
          join public.perfiles p on p.id = ur.usuario_id
         where ur.usuario_id = auth.uid()
           and r.codigo = 'administrador'
           and p.activo = true
    );
$$;

-- Permite operaciones a administradores y empleados.
create or replace function private.es_personal()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
          from public.usuario_roles ur
          join public.roles r on r.id = ur.rol_id
          join public.perfiles p on p.id = ur.usuario_id
         where ur.usuario_id = auth.uid()
           and r.codigo in ('administrador', 'empleado')
           and p.activo = true
    );
$$;

-- Crea el perfil y asigna el rol cliente al registrar una cuenta.
create or replace function private.crear_perfil_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.perfiles (id, nombres, apellidos)
    values (
        new.id,
        coalesce(
            nullif(btrim(new.raw_user_meta_data ->> 'nombres'), ''),
            split_part(coalesce(new.email, 'usuario'), '@', 1)
        ),
        coalesce(nullif(btrim(new.raw_user_meta_data ->> 'apellidos'), ''), '')
    )
    on conflict (id) do nothing;

    insert into public.usuario_roles (usuario_id, rol_id)
    select new.id, id from public.roles where codigo = 'cliente'
    on conflict (usuario_id) do nothing;

    return new;
end;
$$;

